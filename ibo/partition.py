"""Domain partitioning for the IBO framework."""

import itertools

import numpy as np

__all__ = ["divide_bounds", "region_index", "partition_tree_from_data",
           "assign_to_leaves"]


# -----------------------------
# 1. Fixed partition utilities
# -----------------------------
def divide_bounds(bounds, n_parts=2, mode='grid', axis=0):
    """
    Subdivides a bounding box into multiple smaller regions.

    Variables:
    - bounds: (n_dim, 2) array of min/max values for each dimension.
    - n_parts: Number of divisions per dimension (grid) or total (axis).
    - mode: 'grid' for full factorial split, 'axis' for splitting one dimension.
    - axis: The specific dimension index to split if mode is 'axis'.

    Returns the list of region bounds and the division points, the latter in
    the form `region_index` expects.
    """
    bounds = np.array(bounds, dtype=float)
    n_dim = bounds.shape[0]
    n_parts = int(n_parts)

    # Create division points for every dimension
    grid_points = [np.linspace(bounds[d, 0], bounds[d, 1], n_parts + 1)
                   for d in range(n_dim)]
    region_bounds = []

    if n_parts == 1:
        return [bounds], grid_points

    # mode='grid' creates (n_parts^n_dim) small hyper-rectangles
    if mode == 'grid':
        axes = list(range(min(n_dim, 2)))
        for idx in itertools.product(range(n_parts), repeat=len(axes)):
            b = bounds.copy()
            for d, k in zip(axes, idx):
                b[d, 0] = grid_points[d][k]
                b[d, 1] = grid_points[d][k + 1]
            region_bounds.append(b)
    

    # mode='axis' splits only along a single chosen dimension
    elif mode == 'axis':
        for i in range(n_parts):
            b = bounds.copy()
            b[axis, 0] = grid_points[axis][i]
            b[axis, 1] = grid_points[axis][i + 1]
            region_bounds.append(b)

    return region_bounds, grid_points


def region_index(X, grid_points):
    """
    Identifies which grid cell a specific point X belongs to.

    Variables:
    - X: (n, d) array of input coordinates.
    - grid_points: The split points generated by divide_bounds.
    """
    X = np.atleast_2d(X)
    n_dim = X.shape[1]
    n_parts = len(grid_points[0]) - 1
    indices = []

    # Find bin index for each dimension using NumPy digitize
    for d in range(n_dim):
        idx_d = np.digitize(X[:, d], grid_points[d][1:-1], right=True)
        idx_d = np.clip(idx_d, 0, n_parts - 1)
        indices.append(idx_d)

    multi_idx = np.vstack(indices).T
    # Convert multi-dimensional index to a single flat integer
    flat_idx = np.ravel_multi_index(multi_idx.T, dims=[n_parts] * n_dim)
    return flat_idx


# -----------------------------
# 2. Adaptive partition
# -----------------------------
def partition_tree_from_data(X, y, initial_bounds, kernel_func, kernel_args,
                             sigma_estimator, max_depth=3, tau=1.3,
                             min_leaf=8, axes=None, axis_rule='ratio',
                             flat_frac=1e-3):
    """
    Recursive binary partition of `initial_bounds`, driven by the contrast
    between regional scale estimates on the observed data (X, y).

    Variables:
    - X, y: the observations the partition is built from; standardise y
      beforehand so that the contrast is one of local variance rather than of
      absolute magnitude.
    - initial_bounds: (n_dim, 2) array, the region the recursion starts from.
    - kernel_func, kernel_args: the covariance function and its parameters,
      passed through to `sigma_estimator`.
    - sigma_estimator: the regional scale estimator, called as
      sigma_estimator(X, y, kernel_func, **kernel_args).
    - max_depth: no node deeper than this is split.
    - min_leaf: a split is admissible only if both children retain at least
      this many observations, so that sigma-hat is estimable.  The recursion
      also stops at a region holding fewer than 2*min_leaf points.
    - tau: split accepted only if eta_{a*} > tau.
    - axes: the coordinates a split may be tried on; all of them by default.
    - axis_rule: 'ratio'      a* = argmax_a eta_a
                 'max_sigma'  a* = argmax_a max(s_left, s_right)
    - flat_frac: scales below this fraction of the global scale are not
      resolvable and are clipped to it.  Two flat halves then give eta = 1
      exactly, so a flat region is never split on numerical noise.

    Each region is cut at the median of the observations along the chosen
    axis, so the two children hold the same number of points.  Returns the
    list of leaf bounds.
    """

    X = np.atleast_2d(X)
    y = np.asarray(y).flatten()
    n_dim = X.shape[1]
    axes = list(range(n_dim)) if axes is None else list(axes)

    def inside(b):
        return np.all((X >= b[:, 0]) & (X <= b[:, 1]), axis=1)

    # -----------------------------------------------------------------
    # 1. Global scale floor, computed once
    # -----------------------------------------------------------------
    # The floor must be relative to the variation of the whole objective, not
    # to the region being split: on a flat region the local scale is itself
    # negligible, so a locally scaled floor would never bind.
    # A strictly positive floor also guards the degenerate case of a constant
    # objective, where every regional scale is zero and the ratio below would
    # otherwise be 0/0: both halves are then clipped to the floor and give
    # eta = 1, so no split is made.
    global_sigma = float(sigma_estimator(X, y, kernel_func, **kernel_args))
    sigma_floor = max(flat_frac * global_sigma, np.finfo(float).tiny)

    leaves = []
    stack = [(np.array(initial_bounds, dtype=float), 0)]

    while stack:
        b, depth = stack.pop()
        m_here = inside(b)
        n_here = int(np.sum(m_here))

        # stopping rule 1 (depth) and 2 (occupancy)
        if depth >= max_depth or n_here < 2 * min_leaf:
            leaves.append(b)
            continue

        best = None
        for a in axes:
            mid = float(np.median(X[m_here][:, a]))
            bl, br = b.copy(), b.copy()
            bl[a, 1] = mid
            br[a, 0] = mid
            ml, mr = inside(bl), inside(br)

            if ml.sum() < min_leaf or mr.sum() < min_leaf:
                continue                 # this axis cannot be estimated

            sl_raw = float(sigma_estimator(X[ml], y[ml], kernel_func,
                                           **kernel_args))
            sr_raw = float(sigma_estimator(X[mr], y[mr], kernel_func,
                                           **kernel_args))

            # -------------------------------------------------------------
            # 2. Clip the regional scales at the floor
            # -------------------------------------------------------------
            # A scale below the floor is not resolvable.  Clipping rather than
            # skipping gives eta = 1 exactly when both halves are flat, so a
            # flat region is never split on the ratio of two negligible
            # numbers, while a flat half beside a rough one still yields a
            # large eta and is split.
            sl = max(sl_raw, sigma_floor)
            sr = max(sr_raw, sigma_floor)

            eta = max(sl, sr) / min(sl, sr)
            score = eta if axis_rule == 'ratio' else max(sl, sr)

            if best is None or score > best[0]:
                best = (score, eta, bl, br)

        if best is None or best[1] <= tau:
            leaves.append(b)
            continue

        stack.append((best[2], depth + 1))
        stack.append((best[3], depth + 1))

    return leaves


def assign_to_leaves(X, leaves_bounds):
    """
    Index of the first leaf containing each row of X.

    Variables:
    - X: (n, d) array of points.
    - leaves_bounds: the list returned by `partition_tree_from_data` or
      `divide_bounds`.

    A point on a shared boundary is assigned to the first leaf that contains
    it, so the indices form a partition of the rows of X.
    """
    X = np.atleast_2d(X)
    idx = np.zeros(len(X), dtype=int)
    taken = np.zeros(len(X), dtype=bool)
    for r, b in enumerate(leaves_bounds):
        m = np.all((X >= b[:, 0]) & (X <= b[:, 1]), axis=1) & ~taken
        idx[m] = r
        taken |= m
    return idx
